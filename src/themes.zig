//! Built-in reader palettes. No theme files, fonts or I/O are needed at startup.
//! Palette origins and MDF's readability adaptations are documented in themes.md.
const std = @import("std");
pub const Palette = extern struct {
    bg: u32,
    fg: u32,
    panel: u32,
    border: u32,
    link: u32,
    muted: u32,
    selection: u32,
    highlight: u32,
    note: u32,
    tip: u32,
    important: u32,
    warning: u32,
    caution: u32,
};

pub const Preset = enum {
    classic,
    paper,
    terminal,
    nord,
    solarized,
    gruvbox,
    catppuccin,

    pub fn name(self: Preset) []const u8 {
        return switch (self) {
            .classic => "Classic",
            .paper => "Paper",
            .terminal => "Terminal",
            .nord => "Nord",
            .solarized => "Solarized",
            .gruvbox => "Gruvbox",
            .catppuccin => "Catppuccin",
        };
    }

    pub fn fontSize(self: Preset) u16 {
        return switch (self) {
            .classic => 12,
            .paper => 14,
            .terminal => 11,
            .nord => 13,
            .solarized => 14,
            .gruvbox => 12,
            .catppuccin => 13,
        };
    }

