#!/usr/bin/env python3
"""Collect pinned Mermaid/SVG source licenses and their exact source URLs."""
import argparse
from collections import defaultdict
from pathlib import Path
import re
from zig_deps import cached_packages, ROOT

def identity(directory):
    text = (directory/'build.zig.zon').read_text()
    name = re.search(r'\.name\s*=\s*\.([A-Za-z0-9_]+)',text).group(1)
    version = re.search(r'\.version\s*=\s*"([^"]+)"',text).group(1)
    return {'pozeiden':'Pozeiden','svg':'zig-svg'}.get(name,name)+' '+version

def notices():
    roots=[ROOT/'modules/pozeiden',ROOT/'modules/zig-svg']
    packages=cached_packages([path/'build.zig.zon' for path in roots])
    sources=[(identity(path),path,url) for path,url in zip(roots,[
        'https://github.com/sc2in/pozeiden/tree/071fbbb85fb73a06994c163c6093123bd3ac11f6',
        'https://github.com/jcollie/zig-svg/tree/6feaa8d4aee609b0945473931fb27fdcdf1ebfef'])]
    sources += [(identity(record['directory']),record['directory'],record['url']) for _,record in sorted(packages.items())]
    texts=defaultdict(list)
    for title,directory,url in sources:
        files=[path for path in directory.iterdir() if path.is_file() and
            path.name.upper().startswith(('LICENSE','LICENCE','COPYING','COPYRIGHT'))]
        if (directory/'LICENSES').is_dir():
            files += [path for path in (directory/'LICENSES').rglob('*') if path.is_file()]
        if not files:
            if title.startswith('z2d '):
                # z2d's .paths excludes its standard MPL text. Preserve that
                # text in MDF and reproduce the pinned source-header notices.
                texts[(ROOT/'assets/licenses/z2d-MPL-2.0.txt').read_text().strip()].append(title+' / MPL-2.0')
                copyrights=set()
                for source in (directory/'src').rglob('*.zig'):
                    for line in source.read_text().splitlines()[:20]:
                        if 'Copyright' in line or 'SPDX-FileCopyrightText:' in line:
                            copyrights.add(line.lstrip('/! ').strip())
                texts['\n'.join(sorted(copyrights))].append(title+' / source copyright notices')
            else:
                raise ValueError('Missing license files: '+title)
        for path in sorted(set(files)):
            texts[path.read_text().strip()].append(title+' / '+str(path.relative_to(directory)))
    content=('Zig Mermaid layout and SVG rasterizer\n'
        '====================================\n\n'
        'Generated by scripts/mermaid-notices.py from the pinned source graph.\n'
        'Identical license texts are reproduced once with all relevant package names.\n'
        'Pozeiden uses PolyForm Noncommercial 1.0.0; commercial use requires separate permission.\n'
        'zig-svg uses MIT; z2d uses MPL 2.0. Full terms follow.\n'
        'Source for the bundled libraries, including MPL-covered files, is available at these pinned URLs:\n\n')
    for title,_,url in sources:
        content += title+': '+url+'\n'
    for text,names in sorted(texts.items(),key=lambda item:sorted(item[1])[0]):
        content+='\n'+'\n'.join(sorted(set(names)))+'\n'+'-'*72+'\n'+text+'\n'
    return content

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    output=ROOT/'assets/MERMAID-NOTICE.txt'
    content=notices()
    if args.check:
        if output.read_text()!=content:
            raise SystemExit('Diagram notices differ from the pinned sources; run scripts/mermaid-notices.py')
        print('PASS: Zig Mermaid/SVG notices match the pinned source graph')
    else:
        output.write_text(content)
        print('Generated',output,len(content.encode()),'bytes')
