#!/usr/bin/env python3
"""Collect the pinned diagram renderer's license files, deduplicating texts."""
import argparse
from collections import defaultdict
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def notices():
    packages = {(p['name'], p['version']) for p in
                tomllib.loads((ROOT/'frontend/mermaid/Cargo.lock').read_text())['package']}
    packages.remove(('mdf-mermaid', '0.1.0'))
    found = set()
    texts = defaultdict(list)
    for directory in [ROOT/'zig-pkg/mermaid-renderer', *sorted((ROOT/'zig-pkg/mermaid-deps').iterdir())]:
        manifest = directory/'Cargo.toml'
        if not manifest.is_file():
            continue
        package = tomllib.loads(manifest.read_text())['package']
        key = (package['name'], package['version'])
        if key not in packages:
            continue
        found.add(key)
        files = [p for p in directory.iterdir() if p.is_file() and
                 p.name.upper().startswith(('LICENSE', 'LICENCE', 'COPYING', 'COPYRIGHT', 'UNICODE-LICENSE'))]
        for path in list(files):
            if 'AUTHORS' in path.read_text(errors='replace') and (directory/'AUTHORS').is_file():
                files.append(directory/'AUTHORS')
        if not files:
            raise ValueError('Missing license files: '+str(key))
        for path in sorted(set(files)):
            content = path.read_text(errors='strict').strip()
            texts[content].append(f'{key[0]} {key[1]} / {path.name}')
    if found != packages:
        raise ValueError('Missing dependency notices: '+str(packages-found))
    content = ('Native Mermaid renderer and SVG rasterizer\n'
               '========================================\n\n'
               'Generated by scripts/mermaid-notices.py from the locked, vendored sources.\n'
               'Identical license texts are reproduced once with all relevant package names.\n'
               'The renderer has an MDF adaptation that uses only embedded Open Sans metrics.\n\n')
    for text, names in sorted(texts.items(), key=lambda item: sorted(item[1])[0]):
        content += '\n'.join(sorted(names))+'\n'+'-'*72+'\n'+text+'\n\n'
    content += (ROOT/'frontend/mermaid/RUST-LICENSE.txt').read_text()
    return content


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT/'assets/MERMAID-NOTICE.txt'
    content = notices()
    if args.check:
        if output.read_text() != content:
            raise SystemExit('Mermaid notices differ from the locked dependencies; run scripts/mermaid-notices.py')
        print('PASS: Mermaid dependency license notices match the locked sources')
    else:
        output.write_text(content)
        print('Generated', output, len(content.encode()), 'bytes')
